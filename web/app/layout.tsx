import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import Link from "next/link";
import { DESCRIPTION } from "@/lib/copy";
import { Wordmark } from "./brand";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

// Each route sets its own title; this is the fallback and the site-wide
// description.
//
// metadataBase is a plain constant on purpose, and reading VERCEL_URL here
// was a bug. Next already substitutes the right origin for social images
// generated by the file conventions - see getSocialImageMetadataBaseFallback
// in next/dist/lib/metadata/resolvers/resolve-url.js, which resolve-opengraph
// applies whenever the image is a static metadata route EVEN IF metadataBase
// is set. Previews get VERCEL_BRANCH_URL, dev gets localhost, and production
// falls through to this value.
//
// So the only environment this constant decides is production - and
// VERCEL_URL there is the per-DEPLOYMENT hostname, not the custom domain.
// Pointing at it meant every shared link advertised an image on a URL that
// Deployment Protection gates (the scraper gets a 401 and the card renders
// blank), that is unbranded, and that 404s once the deployment is reaped.
//
// openGraph.title is deliberately absent. Setting it at the root freezes it
// site-wide, so /leaderboard would ship <title>SET - Leaderboard</title>
// beside an og:title of just "SET". Left out, each route's own title is used.
export const metadata: Metadata = {
  metadataBase: new URL("https://app.set.trade"),
  title: "SET",
  description: DESCRIPTION,
  openGraph: {
    description: DESCRIPTION,
    siteName: "SET",
    type: "website",
  },
  twitter: {
    card: "summary_large_image",
    description: DESCRIPTION,
  },
};

function Nav() {
  return (
    <nav className="border-b border-white/10">
      <div className="mx-auto flex w-full max-w-5xl items-center gap-5 px-4 py-3.5 sm:px-6">
        <Link
          href="/leaderboard"
          aria-label="SET - home"
          className="text-white transition-opacity hover:opacity-70"
        >
          {/* Height-constrained, width auto: the lockup is 4.25:1, so sizing
              it by width would leave it a different height on every
              breakpoint and misalign it with the links beside it. */}
          <Wordmark className="h-[18px] w-auto" />
        </Link>
        <div className="ml-auto flex items-center gap-4 text-sm">
          <Link href="/leaderboard" className="text-white/50 transition-colors hover:text-white">
            Leaderboard
          </Link>
          <Link
            href="/register"
            className="rounded-md bg-white/10 px-3 py-1.5 font-medium text-white transition-colors hover:bg-white/15"
          >
            Register
          </Link>
        </div>
      </div>
    </nav>
  );
}

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="flex min-h-full flex-col">
        <Nav />
        {children}
      </body>
    </html>
  );
}
