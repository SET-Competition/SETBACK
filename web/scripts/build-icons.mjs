/**
 * Build every icon from lib/marks.ts.
 *
 *   npm run icons
 *
 * Writes app/icon.svg, app/favicon.ico and app/apple-icon.png. Run it
 * whenever the marks or the layout constants below change, and commit what
 * it writes.
 *
 * WHY THIS EXISTS
 *
 * The rasters were once made by shrinking the brand kit's 1000x1000 square
 * PNG, whose padding is tighter than icon.svg's, so the mark shipped about
 * 5% larger on the iOS tile and 12% wider at 32px than in the browser tab -
 * two sizes of one logo depending where you looked. Generating them from
 * icon.svg fixed that; generating icon.svg too removes the last hand copy of
 * the path data, which was the only reason icon.svg could still disagree
 * with lib/marks.ts.
 *
 * TWO SURFACES, TWO TREATMENTS
 *
 * The browser tab and the iOS home screen want opposite things, which is why
 * this script composes two drawings rather than scaling one:
 *
 *   icon.svg      transparent, and nearly full bleed. There is no tile to sit
 *                 inside, so padding is wasted pixels - and at 16px there are
 *                 256 of them. Carries BOTH mark colours and lets
 *                 `prefers-color-scheme` choose, because a transparent icon
 *                 sits on the browser's chrome and this site's own dark theme
 *                 says nothing about that.
 *
 *   apple-icon    opaque, and padded. iOS draws this as a rounded tile and
 *                 composites transparency onto an unpredictable ground, so
 *                 Apple's guidance is a full-bleed opaque icon; the mark then
 *                 needs real margin or the rounding crowds it.
 *
 * favicon.ico is icon.svg flattened, for browsers that will not take an SVG
 * icon. It cannot carry a media query, so it ships the light-chrome colour:
 * librsvg applies the default CSS rule and ignores the unmatched
 * prefers-color-scheme block, which is exactly the variant wanted.
 *
 * sharp is pinned to an exact version in package.json rather than a caret
 * range, which is unusual for a devDependency and is the point: this script's
 * output is committed binaries. A caret lets `npm install` float to a libvips
 * that renders a fractionally different edge, which produces a diff in two
 * PNGs that nobody asked for and nobody can read - and a shift small enough
 * to pass the geometry test is exactly the shift that would go unexplained.
 *
 * Deliberately NOT part of `npm run build`. Vercel would then regenerate
 * committed binaries on every deploy, against whichever libvips the builder
 * happens to ship, and a rendering difference would reach production without
 * appearing in a diff. Generated by hand, reviewed as bytes, pinned by
 * tests/test_brand_assets.py.
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import sharp from "sharp";

const WEB = join(dirname(fileURLToPath(import.meta.url)), "..");
const APP = join(WEB, "app");
const MARKS = join(WEB, "lib", "marks.ts");

/** The square both drawings are composed on. Arbitrary; it only sets precision. */
const CANVAS = 1000;

/**
 * Vertical padding, in canvas units, and the only number here chosen by eye.
 * The mark is taller than it is wide, so this is what bounds it; the
 * horizontal inset falls out of centring.
 *
 * 60 on the favicon is 6%, which is about as tight as a mark can sit without
 * looking clipped, and tight is right when the whole icon is 16 pixels. 190
 * on the Apple tile is 19%, which is roughly where Apple's own icon grid puts
 * the artwork inside the rounded corner.
 */
const FAVICON_MARGIN = 60;
const APPLE_MARGIN = 190;

/** 180 is the size every current iOS device asks for; Apple downscales it. */
const APPLE_SIZE = 180;

/**
 * 16 and 32 only. An ICO can hold any number of sizes, and the browsers that
 * still read this file ask for these two - anything larger is dead weight in
 * a file fetched on every cold page load, and every browser that supports an
 * SVG icon takes icon.svg instead.
 */
const ICO_SIZES = [16, 32];

/**
 * lib/marks.ts is TypeScript and this is a plain Node script, so the values
 * are matched out of the source rather than imported. The alternative is a
 * build step, or a loader flag, to read six string literals.
 *
 * The Python test reads the same file with the same shape of regex, which is
 * NOT a safety net: two mirrored parsers agree on the same wrong answer. A
 * stray string literal inside the LOGOMARK_PATHS block - a comment quoting
 * something, say - is read as a path by both, shipped into icon.svg, and
 * passes every assertion. Hence the shape check below, which is the part
 * that actually catches it.
 */
function marks() {
  const source = readFileSync(MARKS, "utf-8");

  const one = (name) => {
    const found = source.match(
      new RegExp(`export const ${name} =\\s*"([^"]+)";`),
    );
    if (!found) throw new Error(`${name} is missing from lib/marks.ts`);
    return found[1];
  };

  const list = (name) => {
    const block = source.match(
      new RegExp(`export const ${name} = \\[([\\s\\S]*?)\\n\\];`),
    );
    if (!block) throw new Error(`${name} is missing from lib/marks.ts`);
    const found = [...block[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);
    for (const d of found) {
      // SVG path data always opens with a moveto. An invalid `d` renders as
      // nothing at all rather than as an error, so a drawing silently short
      // one stroke is the failure this prevents.
      if (!/^[Mm]\s*-?[\d.]/.test(d)) {
        throw new Error(
          `${name} contains something that is not path data: ${JSON.stringify(
            d.slice(0, 40),
          )}`,
        );
      }
    }
    return found;
  };

  // Split on whitespace RUNS, not on a single space. The Python test uses
  // str.split(), which already does; on "0  0  503  600" this read 0 x 0,
  // computed an infinite scale, and wrote `translate(NaN 60)` into a blank
  // SVG that sharp rasterises without complaint.
  const box = one("LOGOMARK_VIEWBOX").trim().split(/\s+/).map(Number);
  const [, , width, height] = box;
  if (!(width > 0) || !(height > 0)) {
    throw new Error(
      `LOGOMARK_VIEWBOX does not give a positive size: ${JSON.stringify(
        one("LOGOMARK_VIEWBOX"),
      )}`,
    );
  }
  return {
    paths: list("LOGOMARK_PATHS"),
    width,
    height,
    background: one("BRAND_BACKGROUND"),
    onLight: one("MARK_ON_LIGHT"),
    onDark: one("MARK_ON_DARK"),
  };
}

/**
 * Where the mark sits on the canvas for a given vertical margin.
 *
 * Centred on the mark's declared viewBox rather than on the ink it actually
 * covers. The paths fill their box to within a unit, so the two differ by
 * under a tenth of a pixel at 180 - and predicting from the viewBox is what
 * lets the test re-derive this placement without parsing path data.
 */
function layout({ width, height }, margin) {
  const scale = (CANVAS - 2 * margin) / height;
  return {
    scale,
    x: (CANVAS - width * scale) / 2,
    y: margin,
  };
}

const round = (n) => Number(n.toFixed(4));

function group(m, place, fill) {
  return (
    `  <g transform="translate(${round(place.x)} ${round(place.y)}) ` +
    `scale(${round(place.scale)})"${fill ? ` fill="${fill}"` : ""}>\n` +
    m.paths.map((d) => `    <path d="${d}"/>`).join("\n") +
    `\n  </g>`
  );
}

/**
 * The browser-tab icon: no background, and both colours in one file.
 *
 * The fills are CSS rather than `fill` attributes because that is the only
 * place a media query can live. A renderer that ignores CSS - or evaluates
 * no media queries at all, which is what librsvg does when this is flattened
 * into favicon.ico - falls through to the first rule and gets the
 * light-chrome mark, which is the right default for anything old enough to
 * be asking for an ICO.
 */
function faviconSvg(m) {
  const place = layout(m, FAVICON_MARGIN);
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${CANVAS} ${CANVAS}" ` +
    `width="${CANVAS}" height="${CANVAS}">\n` +
    `  <style>\n` +
    `    path { fill: ${m.onLight}; }\n` +
    `    @media (prefers-color-scheme: dark) { path { fill: ${m.onDark}; } }\n` +
    `  </style>\n` +
    group(m, place, null) +
    `\n</svg>\n`
  );
}

/**
 * The iOS tile: opaque, padded, one colour.
 *
 * Drawn in onDark because the tile's own ground IS the brand near-black, so
 * this is a dark surface in the sense that constant means - not because iOS
 * is in dark mode, which it may well not be.
 */
function appleSvg(m) {
  const place = layout(m, APPLE_MARGIN);
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${CANVAS} ${CANVAS}" ` +
    `width="${CANVAS}" height="${CANVAS}">\n` +
    `  <rect width="${CANVAS}" height="${CANVAS}" fill="${m.background}"/>\n` +
    group(m, place, m.onDark) +
    `\n</svg>\n`
  );
}

/**
 * lanczos3 over a 1000px render rather than rendering straight to 16px.
 * Rasterising a thin stroke directly at 16px drops it; rendering large and
 * downsampling turns it into a grey pixel, which is what the eye expects a
 * thin line to look like at that size.
 */
async function raster(svg, size) {
  return sharp(Buffer.from(svg))
    .resize(size, size, { kernel: "lanczos3" })
    .png({ compressionLevel: 9, palette: false })
    .toBuffer();
}

/**
 * PNG-in-ICO: the directory is written by hand because the format is a
 * 6-byte header and a 16-byte entry per image, and the alternative is a
 * dependency that converts formats for a living.
 *
 * Offsets are accumulated rather than computed per entry, so they cannot
 * disagree with the payloads they point at. tests/test_brand_assets.py
 * re-derives them from the file and rejects a gap or an overlap.
 */
function ico(images) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // 1 = icon
  header.writeUInt16LE(images.length, 4);

  let offset = 6 + 16 * images.length;
  const entries = images.map(({ size, data }) => {
    const entry = Buffer.alloc(16);
    entry.writeUInt8(size, 0); // 0 would mean 256
    entry.writeUInt8(size, 1);
    entry.writeUInt8(0, 2); // palette size; 0 for truecolour
    entry.writeUInt8(0, 3); // reserved
    entry.writeUInt16LE(1, 4); // colour planes
    entry.writeUInt16LE(32, 6); // bits per pixel
    entry.writeUInt32LE(data.length, 8);
    entry.writeUInt32LE(offset, 12);
    offset += data.length;
    return entry;
  });

  return Buffer.concat([header, ...entries, ...images.map((i) => i.data)]);
}

function write(name, data) {
  const path = join(APP, name);
  const body = Buffer.isBuffer(data) ? data : Buffer.from(data);

  let before = null;
  try {
    before = createHash("sha256").update(readFileSync(path)).digest("hex");
  } catch {
    // No such file yet; "new" below.
  }
  const after = createHash("sha256").update(body).digest("hex");

  // Only write when the bytes differ, so "unchanged" is the truth rather
  // than a description of identical content with a fresh mtime.
  if (before !== after) writeFileSync(path, body);

  const state =
    before === null ? "new" : before === after ? "unchanged" : "rewritten";
  console.log(
    `${name.padEnd(16)} ${String(body.length).padStart(6)} bytes  ${state}`,
  );
}

const m = marks();
const favicon = faviconSvg(m);

write("icon.svg", favicon);
write("apple-icon.png", await raster(appleSvg(m), APPLE_SIZE));
write(
  "favicon.ico",
  ico(
    await Promise.all(
      ICO_SIZES.map(async (size) => ({
        size,
        data: await raster(favicon, size),
      })),
    ),
  ),
);

console.log("\nfrom web/lib/marks.ts");
