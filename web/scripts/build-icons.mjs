/**
 * Rasterise app/icon.svg into the icon formats that cannot be vectors.
 *
 *   node scripts/build-icons.mjs
 *
 * Run this whenever app/icon.svg changes, and commit what it writes.
 *
 * WHY THIS EXISTS
 *
 * icon.svg is the drawing. apple-icon.png and favicon.ico are the same
 * drawing, flattened, because iOS home screens and `favicon.ico` consumers do
 * not take SVG. Nothing derived them from it: they were made by shrinking the
 * brand kit's 1000x1000 square PNG, whose padding is tighter than icon.svg's,
 * so the mark shipped about 5% larger on the iOS tile and 12% wider at 32px
 * than in the browser tab. Two sizes of the same logo on one site, which is
 * precisely the drift lib/marks.ts and tests/test_brand_assets.py exist to
 * prevent - and it walked straight past them, because the test only checked
 * the rasters' background COLOUR, never their geometry.
 *
 * So the rasters are now generated from icon.svg, and icon.svg is pinned to
 * LOGOMARK_PATHS. One drawing, three files, one source.
 *
 * sharp is pinned to an exact version in package.json rather than a caret
 * range, which is unusual for a devDependency and is the point: this script's
 * output is committed binaries. A caret lets `npm install` float to a libvips
 * that renders a fractionally different edge, which produces a diff in two
 * PNGs that nobody asked for and nobody can read - and a shift small enough
 * to pass the geometry test is exactly the shift that would go unexplained.
 *
 * Deliberately NOT part of `npm run build`. Vercel would then regenerate two
 * committed binaries on every deploy, the output would depend on whichever
 * libvips the builder happens to ship, and a rendering difference would reach
 * production without appearing in a diff. Generated by hand, reviewed as
 * bytes, pinned by a test.
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import sharp from "sharp";

const APP = join(dirname(fileURLToPath(import.meta.url)), "..", "app");
const SOURCE = join(APP, "icon.svg");

/** 180 is the size every current iOS device asks for; Apple downscales it. */
const APPLE_SIZE = 180;

/**
 * 16 and 32 only. An ICO can hold any number of sizes, and the browsers that
 * still read this file ask for these two - anything larger is dead weight in
 * a file that is fetched on every cold page load, and every modern browser
 * takes icon.svg in preference anyway.
 */
const ICO_SIZES = [16, 32];

/**
 * lanczos3 over a 1000px render rather than rendering straight to 16px.
 * Rasterising a 1px-wide stroke directly at 16px drops it; rendering large
 * and downsampling turns it into a grey pixel, which is what the eye expects
 * a thin line to look like at that size.
 */
async function raster(svg, size) {
  return sharp(svg)
    .resize(size, size, { kernel: "lanczos3" })
    .png({ compressionLevel: 9, palette: false })
    .toBuffer();
}

/**
 * PNG-in-ICO: the directory is written by hand because the format is a
 * 6-byte header and a 16-byte entry per image, and the alternative is a
 * dependency that converts formats for a living.
 *
 * Offsets are accumulated rather than computed per entry, so they cannot
 * disagree with the payloads they point at. tests/test_brand_assets.py
 * re-derives them from the file and rejects a gap or an overlap.
 */
function ico(images) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // 1 = icon
  header.writeUInt16LE(images.length, 4);

  let offset = 6 + 16 * images.length;
  const entries = images.map(({ size, data }) => {
    const entry = Buffer.alloc(16);
    entry.writeUInt8(size, 0); // 0 would mean 256
    entry.writeUInt8(size, 1);
    entry.writeUInt8(0, 2); // palette size; 0 for truecolour
    entry.writeUInt8(0, 3); // reserved
    entry.writeUInt16LE(1, 4); // colour planes
    entry.writeUInt16LE(32, 6); // bits per pixel
    entry.writeUInt32LE(data.length, 8);
    entry.writeUInt32LE(offset, 12);
    offset += data.length;
    return entry;
  });

  return Buffer.concat([header, ...entries, ...images.map((i) => i.data)]);
}

function write(name, data) {
  const path = join(APP, name);
  const before = (() => {
    try {
      return createHash("sha256").update(readFileSync(path)).digest("hex");
    } catch {
      return null;
    }
  })();
  const after = createHash("sha256").update(data).digest("hex");

  // Only write when the bytes differ, so "unchanged" is the truth rather
  // than a description of identical content with a fresh mtime.
  if (before !== after) writeFileSync(path, data);
  const state = before === null ? "new" : before === after ? "unchanged" : "rewritten";
  console.log(`${name.padEnd(16)} ${String(data.length).padStart(6)} bytes  ${state}`);
}

const svg = readFileSync(SOURCE);

write(`apple-icon.png`, await raster(svg, APPLE_SIZE));
write(
  `favicon.ico`,
  ico(
    await Promise.all(
      ICO_SIZES.map(async (size) => ({ size, data: await raster(svg, size) })),
    ),
  ),
);

console.log(`\nfrom ${SOURCE.replace(/.*\/web\//, "web/")}`);
